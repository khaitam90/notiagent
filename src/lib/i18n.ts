export function getCurrentLanguage(): AppLanguage {
  if (typeof window === 'undefined') return 'vi'
  return loadAppSettings().language || 'vi'
}

export function applyDocumentLanguage(lang: AppLanguage) {
  if (typeof document === 'undefined') return
  document.documentElement.lang = LANGUAGE_META[lang].htmlLang
}

export function translate(key: string, lang: AppLanguage = getCurrentLanguage()): string {
  return DICTIONARY[lang][key] || DICTIONARY.vi[key] || key
}

export function useAppLanguage(): AppLanguage {
  const [language, setLanguage] = useState<AppLanguage>(() => getCurrentLanguage())

  useEffect(() => {
    const sync = () => setLanguage(getCurrentLanguage())
    sync()
    window.addEventListener('noti-app-settings-changed', sync)
    return () => window.removeEventListener('noti-app-settings-changed', sync)
  }, [])

  return language
}

export function useI18n(): { language: AppLanguage; t: TranslateFn } {
  const language = useAppLanguage()
  const t = useMemo<TranslateFn>(() => (key) => translate(key, language), [language])
  return { language, t }
}
